// Builds supabase/seed.sql: polling stations, a SYNTHETIC demo team and sample
// help requests, using the app's own data and voter generator so every name,
// serial and voter ID matches what the site shows.
//
//   npx tsx scripts/make-seed.ts            # prints the demo password once
//   DEMO_PASSWORD='…' npx tsx scripts/make-seed.ts
//
// The SQL holds only password HASHES. Keep the printed password out of the repo.
import { pbkdf2Sync, randomBytes } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { booths } from '../src/booths'
import { AC_VIEWS, unitsOf, VIEWS } from '../src/geo'
import { votersOf } from '../src/voters'

const OUT = new URL('../supabase/seed.sql', import.meta.url)
const password = process.env.DEMO_PASSWORD ?? randomPassword()
const ITERATIONS = 210000

function randomPassword() {
  const c = 'ABCDEFGHJKMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789'
  return Array.from(randomBytes(12), (b) => c[b % c.length])
    .join('')
    .replace(/(.{4})(.{4})(.{4})/, '$1-$2-$3')
}
const hash = (pw: string) => {
  const salt = randomBytes(16)
  return ['pbkdf2-sha256', ITERATIONS, salt.toString('base64url'), pbkdf2Sync(pw, salt, ITERATIONS, 32, 'sha256').toString('base64url')].join('$')
}
const q = (v: string | number | boolean | null) =>
  v === null ? 'null' : typeof v === 'string' ? `'${v.replace(/'/g, "''")}'` : String(v)

// Deterministic picks so the seed is the same every run (except password hashes).
let seed = 20261110
const rnd = () => {
  seed = (seed + 0x6d2b79f5) | 0
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}
const pick = <T,>(a: T[]) => a[Math.floor(rnd() * a.length)]

// Made-up team names (same style as the sample voters: no real surnames).
const GIVEN = ['Ravi', 'Sunitha', 'Kiran', 'Padma', 'Naresh', 'Swathi', 'Mahesh', 'Lavanya', 'Srinivas', 'Anitha', 'Prakash', 'Divya', 'Raju', 'Kavya', 'Sandeep', 'Madhavi']
const FAMILY = ['Konavali', 'Mederu', 'Tavalu', 'Rekala', 'Pegoti', 'Danoru', 'Saveti', 'Lomari', 'Gopadu', 'Barela', 'Nekoti', 'Vasupu']
const person = () => `${pick(FAMILY)} ${pick(GIVEN)}`
const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

const lines: string[] = [
  '-- GENERATED by scripts/make-seed.ts — synthetic demo data. Re-run the script, do not edit.',
  '-- Run after migrations/001_roles_and_help_requests.sql in Supabase → SQL Editor.',
  'begin;',
  'truncate request_events, help_requests, assignments, app_users, booths restart identity cascade;',
  '',
  '-- Polling stations and their ward / mandal',
]

// Booths ---------------------------------------------------------------------
for (const b of booths)
  lines.push(
    `insert into booths (id, ac, ps_no, unit_id, unit_name, name) values (${q(b.id)}, ${b.ac}, ${b.no}, ${q(b.unitId ?? null)}, ${q(b.unitName ?? null)}, ${q(b.name)});`,
  )

// Team -------------------------------------------------------------------------
interface U {
  id: number
  username: string
  name: string
  role: 'admin' | 'unit_lead' | 'booth_lead'
  phone: string | null
}
const users: U[] = []
const add = (username: string, name: string, role: U['role']) => {
  const u = { id: users.length + 1, username, name, role, phone: `9${String(Math.floor(rnd() * 1e9)).padStart(9, '0')}` }
  users.push(u)
  return u
}
const admin = add('admin', 'Admin (demo)', 'admin')
const assign: { user: number; unit?: string; booth?: string }[] = []
const leadOfBooth = new Map<string, U>()
const unitLeadOf = new Map<string, U>()

for (const v of AC_VIEWS) {
  const ac = VIEWS[v].ac!
  for (const unit of unitsOf(v)) {
    const lead = add(`lead.${slug(unit.name)}`, person(), 'unit_lead')
    assign.push({ user: lead.id, unit: unit.unitId! })
    unitLeadOf.set(unit.unitId!, lead)
    // Booth leads: each covers 2–4 booths; ~15% of booths left without a lead (coverage gaps).
    const unitBooths = booths.filter((b) => b.unitId === unit.unitId)
    let i = 0
    let n = 1
    while (i < unitBooths.length) {
      const size = 2 + Math.floor(rnd() * 3)
      const group = unitBooths.slice(i, i + size)
      i += size
      if (rnd() < 0.15) continue
      const bl = add(`bl.${slug(unit.name)}.${String(n++).padStart(2, '0')}`, person(), 'booth_lead')
      for (const b of group) {
        assign.push({ user: bl.id, booth: b.id })
        leadOfBooth.set(b.id, bl)
      }
    }
  }
  void ac
}

lines.push('', `-- Team: ${users.length} demo accounts (all share one demo password; hashes only)`)
for (const u of users)
  lines.push(
    `insert into app_users (id, username, name, role, password_hash, phone) overriding system value values (${u.id}, ${q(u.username)}, ${q(u.name)}, ${q(u.role)}, ${q(hash(password))}, ${q(u.phone)});`,
  )
lines.push(`select setval(pg_get_serial_sequence('app_users', 'id'), ${users.length});`)
lines.push('', '-- Who leads what')
for (const a of assign)
  lines.push(`insert into assignments (user_id, unit_id, booth_id) values (${a.user}, ${q(a.unit ?? null)}, ${q(a.booth ?? null)});`)

// Help requests -------------------------------------------------------------------
const SCHEMES = ['aasara', 'kalyana_lakshmi', 'indiramma_house', 'rythu_bharosa', 'mahalakshmi', 'gruha_jyothi', 'arogyasri', 'ration_card', 'other']
const NEEDS: Record<string, string[]> = {
  aasara: ['Old-age pension not started after turning 57', 'Widow pension application help', 'Pension stopped, needs re-verification'],
  kalyana_lakshmi: ['Daughter’s marriage next month, needs application help', 'Documents for Shaadi Mubarak application'],
  indiramma_house: ['Family lives in rented room, wants to apply for a house', 'Needs help with house site documents'],
  rythu_bharosa: ['Land records not linked, payment not received', 'New pattadar passbook for application'],
  mahalakshmi: ['Gas subsidy not reflected', 'Needs help registering for Mahalakshmi'],
  gruha_jyothi: ['Free electricity not applied on bill', 'Meter in landlord’s name, needs guidance'],
  arogyasri: ['Needs Aarogyasri card for upcoming surgery', 'Hospital not accepting card, needs help'],
  ration_card: ['New ration card for married son’s family', 'Name correction on ration card', 'Add newborn to ration card'],
  other: ['Caste / income certificate for scholarship', 'Disability certificate application', 'Help with Aadhaar address update'],
}
const STATUSES = ['new', 'new', 'documents_pending', 'documents_pending', 'applied', 'applied', 'resolved', 'not_eligible', 'closed'] as const
const ORDER = ['new', 'documents_pending', 'applied'] as const
const ledBooths = booths.filter((b) => leadOfBooth.has(b.id))
let reqId = 0
let evId = 0
const reqLines: string[] = []
const evLines: string[] = []
const usedVoter = new Set<string>()
const now = Date.parse('2026-11-08T10:00:00Z')
for (let k = 0; k < 300; k++) {
  const b = pick(ledBooths)
  const voters = votersOf(b)
  const v = pick(voters)
  const scheme = pick(SCHEMES)
  const key = `${b.id}|${v.serial}|${scheme}`
  if (usedVoter.has(key)) continue
  usedVoter.add(key)
  const by = leadOfBooth.get(b.id)!
  const status = pick([...STATUSES])
  const created = new Date(now - Math.floor(rnd() * 40) * 86400000 - Math.floor(rnd() * 36000) * 1000)
  const mobile = rnd() < 0.6 ? `${pick(['9', '8', '7', '6'])}${String(Math.floor(rnd() * 1e9)).padStart(9, '0')}` : null
  reqId++
  reqLines.push(
    `insert into help_requests (id, booth_id, voter_serial, voter_ref, voter_name, scheme_code, need, contact_mobile, consent, consent_at, status, created_by, assigned_to, created_at, updated_at) overriding system value values (${reqId}, ${q(b.id)}, ${v.serial}, ${q(v.id)}, ${q(v.name)}, ${q(scheme)}, ${q(pick(NEEDS[scheme]))}, ${q(mobile)}, true, ${q(created.toISOString())}, ${q(status)}, ${by.id}, ${by.id}, ${q(created.toISOString())}, ${q(created.toISOString())});`,
  )
  evLines.push(
    `insert into request_events (id, request_id, user_id, action, to_status, at) overriding system value values (${++evId}, ${reqId}, ${by.id}, 'created', 'new', ${q(created.toISOString())});`,
  )
  // History: walk the request forward to its current status.
  const path: string[] = status === 'new' ? [] : [...ORDER.slice(1, ORDER.indexOf(status as (typeof ORDER)[number]) + 1 || 3)]
  if (['resolved', 'not_eligible', 'closed'].includes(status)) path.push(status)
  let prev = 'new'
  let t = created.getTime()
  for (const s of path) {
    t += (1 + Math.floor(rnd() * 6)) * 86400000
    const actor = rnd() < 0.3 ? unitLeadOf.get(b.unitId!)! : by
    evLines.push(
      `insert into request_events (id, request_id, user_id, action, from_status, to_status, at) overriding system value values (${++evId}, ${reqId}, ${actor.id}, 'status', ${q(prev)}, ${q(s)}, ${q(new Date(Math.min(t, now)).toISOString())});`,
    )
    prev = s
  }
  if (path.length) reqLines.push(`update help_requests set updated_at = ${q(new Date(Math.min(t, now)).toISOString())} where id = ${reqId};`)
}
lines.push('', `-- ${reqId} sample help requests (synthetic voters, consent recorded)`, ...reqLines, ...evLines)
lines.push(`select setval(pg_get_serial_sequence('help_requests', 'id'), ${reqId});`)
lines.push(`select setval(pg_get_serial_sequence('request_events', 'id'), ${evId});`)
lines.push('commit;', '')
writeFileSync(OUT, lines.join('\n'))

const covered = new Set(assign.filter((a) => a.booth).map((a) => a.booth)).size
console.log(`Wrote supabase/seed.sql: ${booths.length} booths, ${users.length} users (${covered}/${booths.length} booths with a booth lead), ${reqId} help requests.`)
console.log(`Sample logins: admin · ${users.find((u) => u.role === 'unit_lead')!.username} · ${users.find((u) => u.role === 'booth_lead')!.username}`)
if (!process.env.DEMO_PASSWORD) console.log(`Demo password (all demo accounts — keep out of the repo): ${password}`)
void admin
