#!/usr/bin/env node
// Packs supabase/migrations/*.sql and supabase/seed.sql into a TypeScript module
// so the /api/setup function (and /setup.html) can create the tables and load the
// demo data on the live database without anyone copying SQL by hand.
//
//   node scripts/make-setup-sql.mjs      (run after scripts/make-seed.ts)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const migDir = resolve(root, 'supabase/migrations')
const migrations = readdirSync(migDir)
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .map((f) => ({ name: f, sql: readFileSync(resolve(migDir, f), 'utf8') }))
const seed = readFileSync(resolve(root, 'supabase/seed.sql'), 'utf8')

const out = `// GENERATED by scripts/make-setup-sql.mjs from supabase/*.sql — do not edit.
export const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(migrations)}
export const SEED: string = ${JSON.stringify(seed)}
`
writeFileSync(resolve(root, 'netlify/lib/setup-sql.generated.ts'), out)
console.log(`Packed ${migrations.length} migration(s) and seed (${Math.round(seed.length / 1024)} KB) into netlify/lib/setup-sql.generated.ts`)
